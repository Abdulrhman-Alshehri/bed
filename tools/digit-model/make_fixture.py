"""Synthetic test bands (never real documents) with the Python reader's results, for the TypeScript tests."""
import base64, json, os, random, zlib, datetime
import numpy as np, cv2
os.environ.setdefault('MODEL', 'model-quantized.json')
import gen, reader, core, eval_synth as es

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'src', 'ocr', '__fixtures__', 'digit-bands.json')
os.makedirs(os.path.dirname(OUT), exist_ok=True)
cases = []
specs = [('1985-11-03', 'gregorian', 'amiri-700'), ('1410-10-17', 'hijri', 'mada-400'), ('1999-02-28', 'gregorian', 'readex-pro-700'), ('1376-03-09', 'hijri', 'harmattan-700')]
for i, (iso, cal, font) in enumerate(specs):
    rng = random.Random(40 + i); np.random.seed(40 + i)
    es.BUCKET = (16, 22)
    font_path = [f for f in gen.TEST_FONTS if font in f][0]
    small, bbox = es.render(rng, font_path, iso, cal == 'hijri')
    band, (x0, y0, s) = reader.band_for_label(small.astype(np.float32), bbox)
    band = np.clip(band, 0, 255).astype(np.uint8)
    label_x = (bbox['x0'] - x0) * s
    # Python reference on exactly these pixels
    gs = core.glyphs(core.binarize(band.astype(np.float32)))
    rough = core.line_metrics(gs)[0]
    gs2 = [g for g in gs if g['x1'] <= label_x + 2]
    grp = [g for g in reversed(reader.groups(gs2, gap=1.0 * rough)) if len(g) >= 5][0]
    grp = reader.split_unclear(grp)
    P, H, cy = reader.classify_group(grp)
    best = reader.decode(P, today=datetime.date(2026, 10, 30))
    cases.append({
        'name': f'{cal} {iso} ({font})', 'width': band.shape[1], 'height': band.shape[0], 'labelX': label_x,
        'gray': base64.b64encode(zlib.compress(band.tobytes(), 9)).decode(),
        'glyphCount': len(grp),
        'firstGlyphFeatures': [round(float(v), 5) for v in core.features(grp[0], H, cy)],
        'probabilities': [[round(float(v), 4) for v in p] for p in P],
        'decoded': best[0][1] if best else None,
        # Same rule as the app: probable enough and at least 2 (log) ahead of the next valid date.
        'confident': bool(best) and float(best[0][0]) >= -3 and float(best[0][0] - (best[1][0] if len(best) > 1 else -30)) >= 2,
    })
    print(cases[-1]['name'], '→', cases[-1]['decoded'], 'glyphs', len(grp), 'band', band.shape)
json.dump({'note': 'Synthetic rendered dates (fonts not used in training), not real documents. Generated by tools/digit-model/make_fixture.py.', 'cases': cases}, open(OUT, 'w'))
print(os.path.getsize(OUT), 'bytes')

"""Writes the trained model as src/ocr/digitModel.ts with 8-bit weights (about 4× smaller than floats)."""
import base64, json, os, sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'model.json')
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, '..', '..', 'src', 'ocr', 'digitModel.ts')
M = json.load(open(src))


def quantize(name):
    w = np.array(M[name], np.float32)
    scale = float(np.abs(w).max() / 127)
    q = np.clip(np.round(w / scale), -127, 127).astype(np.int8)
    return {'scale': round(scale, 8), 'data': base64.b64encode(q.tobytes()).decode()}, q.astype(np.float32) * scale


w1, W1 = quantize('W1')
w2, W2 = quantize('W2')
model = {
    'inputs': W1.shape[0] if W1.ndim > 1 else len(M['W1']), 'hidden': len(M['b1']), 'classes': len(M['b2']),
    'w1': w1, 'b1': [round(v, 5) for v in M['b1']], 'w2': w2, 'b2': [round(v, 5) for v in M['b2']],
}
model['inputs'] = len(M['W1'])
with open(out, 'w') as f:
    f.write('// Generated by tools/digit-model/export.py from the trained model. Do not edit by hand.\n')
    f.write('// Classes: ٠ ١ ٢ ٣ ٤ ٥ ٦ ٧ ٨ ٩ / other. Weights are 8-bit integers × scale, row-major (inputs × outputs).\n')
    f.write('export const DIGIT_MODEL = ' + json.dumps(model, ensure_ascii=False) + ' as const;\n')
json.dump({'W1': W1.reshape(len(M['W1']), -1).tolist(), 'b1': M['b1'], 'W2': W2.reshape(len(M['W2']), -1).tolist(), 'b2': M['b2'],
           'classes': M['classes'], 'grid': M['grid'], 'normH': M['normH']}, open(os.path.join(HERE, 'model-quantized.json'), 'w'))
print('wrote', out, os.path.getsize(out), 'bytes')
